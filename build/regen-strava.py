#!/usr/bin/env python3
"""Rewrite strava.js with the latest activity.

strava.js is generated — the page reads it for the caption under the homepage
photo. It is a JS literal rather than JSON for the same reason the globe's
country data is: fetch() of a local JSON file is blocked by CORS over file://,
and this site works from the filesystem.

Run by .github/workflows/strava.yml on a schedule, with credentials in repo
secrets:

    STRAVA_CLIENT_ID / STRAVA_CLIENT_SECRET / STRAVA_REFRESH_TOKEN

Without them it exits 0 and writes nothing, so the scheduled job is a green
no-op until the one-time setup (see README) has been done — a red X four times
a day for a feature that isn't configured yet helps nobody.

The output carries only the activity TYPE, duration and start time — never the
user-entered activity name, which routinely leaks routes and home locations,
and this file is published. "X days ago" is computed in the browser from
`start`, so nothing here needs to change for the caption to stay current
between refreshes; the file only changes when a new activity appears, which is
what keeps the commit history quiet.

Test the transform without the network:

    python3 build/regen-strava.py --from-file fixture.json

where the fixture is the JSON array the /athlete/activities endpoint returns.
"""
import json
import os
import pathlib
import sys
import urllib.parse
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "strava.js"

HEADER = (
    "/* ===== GENERATED by build/regen-strava.py — DO NOT HAND-EDIT =====\n"
    "   Latest Strava activity: type + duration + start, nothing else.\n"
    "   Rewritten on a schedule by .github/workflows/strava.yml.\n"
    "   ================================================================ */\n"
)


def fetch_activities():
    cid = os.environ.get("STRAVA_CLIENT_ID")
    secret = os.environ.get("STRAVA_CLIENT_SECRET")
    refresh = os.environ.get("STRAVA_REFRESH_TOKEN")
    if not (cid and secret and refresh):
        print("strava secrets not configured; nothing to do.")
        sys.exit(0)

    body = urllib.parse.urlencode({
        "client_id": cid,
        "client_secret": secret,
        "refresh_token": refresh,
        "grant_type": "refresh_token",
    }).encode()
    req = urllib.request.Request("https://www.strava.com/oauth/token", data=body)
    with urllib.request.urlopen(req, timeout=30) as r:
        token = json.loads(r.read().decode())["access_token"]

    req = urllib.request.Request(
        "https://www.strava.com/api/v3/athlete/activities?per_page=1",
        headers={"Authorization": "Bearer " + token},
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())


def main() -> None:
    if len(sys.argv) == 3 and sys.argv[1] == "--from-file":
        activities = json.loads(pathlib.Path(sys.argv[2]).read_text())
    elif len(sys.argv) == 1:
        activities = fetch_activities()
    else:
        sys.exit("usage: regen-strava.py [--from-file activities.json]")

    if activities:
        a = activities[0]
        data = {
            # sport_type is the modern field ("TrailRun", "WeightTraining");
            # type is the legacy fallback.
            "type": a.get("sport_type") or a.get("type") or "workout",
            "moving_s": int(a.get("moving_time") or 0),
            "start": a.get("start_date"),
        }
        literal = json.dumps(data, separators=(", ", ": "))
    else:
        literal = "null"

    content = HEADER + "var STRAVA = " + literal + ";\n"
    if OUT.exists() and OUT.read_text() == content:
        print("strava.js already up to date; nothing written.")
        return
    OUT.write_text(content)
    print(f"rewrote {OUT.name}: {literal}")


if __name__ == "__main__":
    main()
